import assert from 'node:assert/strict';
import { preparePassage, SentenceSession } from '../src/sentence-core.ts';
import { createSentenceProgress } from '../src/sentence-progress.ts';

const exact = (text) => preparePassage(text,'exact').sentences;
assert.deepEqual(exact('Sleep Token[1] is a band—formed in London.[2]'),['Sleep Token is a band-formed in London.']);
assert.deepEqual(exact('[Read more](https://example.com) [\\[1\\]](https://example.com/#cite_note-1)'),['Read more']);
assert.deepEqual(exact('- Practice slowly.\n- Keep your hands relaxed.'),['Practice slowly.','Keep your hands relaxed.']);
assert.deepEqual(exact('1. Find F and J\n2. Return home'),['Find F and J','Return home']);
assert.deepEqual(exact('Dr. Lee paid 3.14 coins. Then she left.'),['Dr. Lee paid 3.14 coins.','Then she left.']);
assert.deepEqual(exact('2026 was a strange year.'),['2026 was a strange year.']);
assert.deepEqual(exact('She said, "Go!" Then they left.'),['She said, "Go!"','Then they left.']);
assert.deepEqual(exact('Line one? Line two!'),['Line one?','Line two!']);
assert.deepEqual(exact('- [x] First item\n  its continuation\n  - Nested item'),['First item its continuation','Nested item']);
assert.deepEqual(exact('Music—especially metal stays loud.'),['Music-especially metal stays loud.']);
assert.deepEqual(preparePassage('Hi—there!','gentle').sentences,['Hi-there!']);
assert.deepEqual(preparePassage('Alice met Dr. Lee in London. NASA called.','gentle').sentences,['Alice met Dr. Lee in London.','NASA called.']);
const gentle = new SentenceSession(['Alice'], 'gentle');
for (const key of 'alic') assert.equal(gentle.input(key),'correct');
assert.equal(gentle.input('e'),'finished');
assert.equal(new SentenceSession(['Alice'],'exact').input('a'),'wrong');
assert.throws(()=>preparePassage('☃','exact'));
assert.throws(()=>preparePassage('café','gentle'));
assert.deepEqual(preparePassage("Don't stop.",'gentle').sentences,["Don't stop."]);
assert.deepEqual(preparePassage('I’ve met Alice. She said, "I’m ready!"','gentle').sentences,["I've met Alice.",'She said, "I\'m ready!"']);
for(const style of ['gentle','exact']){
  const text='Mix apple, pear (ripe), and kiwi: sweet-tart; fresh!';
  assert.deepEqual(preparePassage(text,style).sentences,[text]);
}
const punctuated=new SentenceSession(preparePassage('Go, now!','gentle').sentences,'gentle');
punctuated.input('g');punctuated.input('o');
assert.equal(punctuated.input(' '),'wrong','punctuation must actually be typed');
punctuated.input('Backspace');
for(const key of ', now!')punctuated.input(key);
assert.equal(punctuated.completed,true);
const contraction = new SentenceSession(preparePassage("I've",'gentle').sentences,'gentle');
for (const key of "i'v") assert.equal(contraction.input(key),'correct');
assert.equal(contraction.input('e'),'finished');
assert.throws(()=>preparePassage('a'.repeat(651),'exact'));

const session = new SentenceSession(['a b','cd']);
assert.equal(session.input('a',1000),'correct');
assert.equal(session.input('x',1200),'wrong');
assert.equal(session.input(' ',1300),'wrong');
session.input('Backspace'); session.input('Backspace');
assert.equal(session.snapshot().error,'');
assert.equal(session.input(' ',1400),'correct');
assert.equal(session.input('b',1500),'slash');
assert.equal(session.input('c',1501),'correct');
assert.equal(session.input('d',1502),'finished');
assert.equal(session.input('d',1503),'ignored');
assert.equal(session.snapshot().index,1);
assert.equal(session.snapshot().attempts,7);
assert.equal(session.active,502);
let raw = '';
const storage = { getItem: () => raw, setItem: (_key,value) => { raw=value; } };
const progress = createSentenceProgress(storage);
progress.add({style:'gentle',attempts:7,correct:5,characters:5,sentences:1,total:2,activeMs:502,complete:false});
assert.equal(createSentenceProgress(storage).records()[0].sentences,1);
assert.equal(raw.includes('a b'),false);
progress.reset();assert.equal(createSentenceProgress(storage).records().length,0);
console.log('Passed: article cleanup, list boundaries, punctuation modes, correction, immediate next-sentence typing, and single completion.');
